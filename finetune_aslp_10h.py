import soundfile as sf
if 'model' not in globals():
    from unsloth import FastLanguageModel
    from peft import PeftModel
    base_model, tokenizer = FastLanguageModel.from_pretrained(model_name=MODEL_ID, max_seq_length=MAX_LENGTH, dtype=None, load_in_4bit=LOAD_IN_4BIT)
    model = PeftModel.from_pretrained(base_model, str(OUTPUT_DIR / 'adapter_final'))
FastLanguageModel.for_inference(model)
model.eval()
prompt_ids = [128259] + tokenizer.encode(URDU_TEXT, add_special_tokens=True) + [128009, 128260, 128261, 128257]
inputs = torch.tensor([prompt_ids], dtype=torch.long, device='cuda')
with torch.inference_mode():
    output = model.generate(input_ids=inputs, max_new_tokens=MAX_NEW_TOKENS, do_sample=True, temperature=0.6, top_p=0.95, repetition_penalty=1.1, eos_token_id=128258, pad_token_id=128263, use_cache=True)
new_ids = output[0, inputs.shape[1]:].tolist()
if 128258 in new_ids: new_ids = new_ids[:new_ids.index(128258)]
frames = []
offsets = [0, 4096, 8192, 12288, 16384, 20480, 24576]
for i in range(0, len(new_ids)-6, 7):
    block = new_ids[i:i+7]
    if any(not 0 <= token - 128266 - offset < 4096 for token, offset in zip(block, offsets)):
        break
    frames.append([token - 128266 - offset for token, offset in zip(block, offsets)])
if not frames: raise RuntimeError(f'No complete SNAC frames generated. First output IDs: {new_ids[:20]}')
codes = [
    torch.tensor([[f[0] for f in frames]], dtype=torch.long),
    torch.tensor([[v for f in frames for v in (f[1], f[4])]], dtype=torch.long),
    torch.tensor([[v for f in frames for v in (f[2], f[3], f[5], f[6])]], dtype=torch.long),
]
decoder = SNAC.from_pretrained('hubertsiuzdak/snac_24khz').eval().cpu()
with torch.inference_mode(): waveform = decoder.decode(codes).squeeze().cpu().numpy()
audio_path = OUTPUT_DIR / 'urdu_test.wav'
sf.write(audio_path, waveform, 24000)
print('Saved:', audio_path, '| seconds:', round(len(waveform)/24000, 2), '| frames:', len(frames))
