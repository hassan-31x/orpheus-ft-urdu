"""## 3. Check and clean manifests
Only NFC normalization, whitespace cleanup, and control removal are applied. The Urdu wording and punctuation stay intact. The existing speaker IDs are unreliable as voice identities, so prompts contain text alone. Review the printed examples and listen to `samples_to_review.csv` before claiming quality.

"""

import pandas as pd, unicodedata, wave, re
from IPython.display import Audio, display
def clean_text(s):
    s = unicodedata.normalize('NFC', str(s))
    s = ''.join(c for c in s if unicodedata.category(c) != 'Cc' or c in '\t\n')
    return ' '.join(s.split())
def checked_split(name):
    df = pd.read_csv(DATA_DIR / f'stage1_{name}.csv', dtype=str, keep_default_na=False)
    assert {'audio','text'} <= set(df.columns)
    df = df[['audio','text']].copy()
    df['text'] = df['text'].map(clean_text)
    bad, durations = [], []
    for i, row in df.iterrows():
        p = Path(row.audio)
        if p.is_absolute() or '..' in p.parts or not row.text or not re.search('[\u0600-\u06ff]', row.text):
            bad.append((i, 'path/text')); durations.append(0); continue
        path = DATA_DIR / p
        try:
            with wave.open(str(path), 'rb') as w:
                duration = w.getnframes()/w.getframerate()
                if w.getframerate()!=24000 or w.getnchannels()!=1 or w.getsampwidth()!=2 or not 1.9<=duration<=10.1:
                    bad.append((i, 'audio format/duration'))
            durations.append(duration)
        except Exception as e:
            bad.append((i, str(e))); durations.append(0)
    if bad: raise ValueError(f'{name}: {len(bad)} invalid rows, first: {bad[:5]}')
    if df.audio.duplicated().any(): raise ValueError(f'{name}: duplicate audio paths')
    df['duration'] = durations
    print(name, len(df), f'{sum(durations)/3600:.3f} hours')
    return df
train_df = checked_split('train')
