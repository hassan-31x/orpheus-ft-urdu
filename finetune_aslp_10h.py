"""## 4. Encode speech with SNAC; cache in Drive
Each split is saved in 100-row Parquet chunks, so rerunning after a disconnect resumes completed chunks. Do not change the manifests or model/token format while reusing a cache directory; choose a new `CACHE_DIR` if you do. A failed chunk is retried, and invalid rows cause an error rather than being silently dropped.

"""

from unsloth import FastLanguageModel, is_bfloat16_supported  # import before transformers
import torch, numpy as np, soundfile as sf, gc
from snac import SNAC
from transformers import AutoTokenizer, AutoConfig
from tqdm.auto import tqdm
assert torch.cuda.is_available(), 'Enable a Colab GPU runtime.'
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
model_vocab_size = AutoConfig.from_pretrained(MODEL_ID).vocab_size
snac = SNAC.from_pretrained('hubertsiuzdak/snac_24khz').eval().cuda()
SPECIAL = dict(end_text=128009, start_speech=128257, end_speech=128258, start_human=128259, end_human=128260, start_ai=128261, end_ai=128262)
AUDIO_BASE = 128266
def encode_row(row):
    audio, sr = sf.read(DATA_DIR / row.audio, dtype='float32')
    assert sr == 24000 and audio.ndim == 1 and np.isfinite(audio).all()
    signal = torch.from_numpy(audio).to('cuda').view(1,1,-1)
    with torch.inference_mode(): codes = snac.encode(signal)
    c0, c1, c2 = [c[0].cpu().tolist() for c in codes]
    assert len(c1)>=2*len(c0) and len(c2)>=4*len(c0)
    frames = []
    for i in range(len(c0)):
        frame = [c0[i], c1[2*i]+4096, c2[4*i]+8192, c2[4*i+1]+12288, c1[2*i+1]+16384, c2[4*i+2]+20480, c2[4*i+3]+24576]
        if not frames or frame[0] != frames[-1][0]: frames.append(frame)
    audio_ids = [AUDIO_BASE + code for frame in frames for code in frame]
    text_ids = tokenizer.encode(row.text, add_special_tokens=True)
    ids = [SPECIAL['start_human']] + text_ids + [SPECIAL['end_text'], SPECIAL['end_human'], SPECIAL['start_ai'], SPECIAL['start_speech']] + audio_ids + [SPECIAL['end_speech'], SPECIAL['end_ai']]
    assert len(ids) <= MAX_LENGTH, f'Sequence too long ({len(ids)}); adjust MAX_LENGTH or exclude clip after review'
    assert max(ids) < model_vocab_size, f'Audio token exceeds model vocabulary: {max(ids)} >= {model_vocab_size}'
    return {'input_ids': ids, 'attention_mask': [1]*len(ids), 'labels': ids.copy()}
def encode_split(df, name, chunk_size=100):
    folder = CACHE_DIR / name
    folder.mkdir(parents=True, exist_ok=True)
    for start in tqdm(range(0, len(df), chunk_size), desc=name):
        dest = folder / f'{start:06d}.parquet'
        if dest.exists():
            if len(pd.read_parquet(dest)) == min(chunk_size, len(df)-start): continue
            raise ValueError(f'Incomplete cache chunk: {dest}; inspect it before retrying')
        rows = [encode_row(row) for row in df.iloc[start:start+chunk_size].itertuples()]
        temp = folder / f'{start:06d}.tmp.parquet'
        pd.DataFrame(rows).to_parquet(temp, index=False)
        temp.replace(dest)
        del rows
    return sorted(str(p) for p in folder.glob('*.parquet'))
train_files = encode_split(train_df, 'train')
val_files = encode_split(val_df, 'validation')
del snac
gc.collect(); torch.cuda.empty_cache()
print('Cached chunks:', len(train_files), len(val_files))

"""## 5. Train for one epoch with Drive checkpoints
Unsloth runs LoRA over the English pretrained Orpheus model. The prepared Parquet files contain real audio tokens; text-only tokenization cannot teach speech. Dynamic padding keeps memory use down. Rerunning resumes the latest Drive checkpoint. The final `adapter_final` needs the same base `MODEL_ID` for inference.

"""

from unsloth import FastLanguageModel, is_bfloat16_supported
from datasets import load_dataset
from transformers import Trainer, TrainingArguments
from transformers.trainer_utils import get_last_checkpoint
ds = load_dataset('parquet', data_files={'train': train_files, 'validation': val_files})
assert len(ds['train']) == len(train_df) and len(ds['validation']) == len(val_df)
print(ds)
PAD = tokenizer.pad_token_id if tokenizer.pad_token_id is not None else tokenizer.eos_token_id
def collate(examples):
    width = max(len(x['input_ids']) for x in examples)
    return {
        'input_ids': torch.tensor([list(x['input_ids']) + [PAD]*(width-len(x['input_ids'])) for x in examples], dtype=torch.long),
        'attention_mask': torch.tensor([list(x['attention_mask']) + [0]*(width-len(x['attention_mask'])) for x in examples], dtype=torch.long),
        'labels': torch.tensor([list(x['labels']) + [-100]*(width-len(x['labels'])) for x in examples], dtype=torch.long),
    }
model, train_tokenizer = FastLanguageModel.from_pretrained(model_name=MODEL_ID, max_seq_length=MAX_LENGTH, dtype=None, load_in_4bit=LOAD_IN_4BIT)
assert len(train_tokenizer) == len(tokenizer), 'Training tokenizer differs from preprocessing tokenizer'
model = FastLanguageModel.get_peft_model(model, r=16, target_modules=['q_proj','k_proj','v_proj','o_proj','gate_proj','up_proj','down_proj'], lora_alpha=32, lora_dropout=0, bias='none', use_gradient_checkpointing='unsloth', random_state=3407)
model.print_trainable_parameters()
args = TrainingArguments(output_dir=str(OUTPUT_DIR), num_train_epochs=EPOCHS, per_device_train_batch_size=1, gradient_accumulation_steps=8, learning_rate=2e-4, lr_scheduler_type='cosine', warmup_ratio=0.03, fp16=not is_bfloat16_supported(), bf16=is_bfloat16_supported(), logging_steps=25, save_strategy='steps', save_steps=SAVE_STEPS, save_total_limit=3, eval_strategy='no', report_to='none', optim='adamw_8bit', remove_unused_columns=False, seed=3407)
trainer = Trainer(model=model, args=args, train_dataset=ds['train'], data_collator=collate)
last = get_last_checkpoint(str(OUTPUT_DIR))
print('Resuming from:', last or 'start')
result = trainer.train(resume_from_checkpoint=last)
trainer.save_model(str(OUTPUT_DIR / 'adapter_final'))
train_tokenizer.save_pretrained(str(OUTPUT_DIR / 'adapter_final'))
trainer.save_metrics('train', result.metrics)
print('Saved adapter:', OUTPUT_DIR / 'adapter_final')

